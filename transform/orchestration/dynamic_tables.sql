-- 1. Canonical Layer Dynamic Table
CREATE OR REPLACE DYNAMIC TABLE {DATABASE}.{SCHEMA_CANONICAL}.DT_SALES_FACT
  TARGET_LAG = '10 MINUTES'
  WAREHOUSE = {WAREHOUSE}
AS
WITH combined_sales AS (
    SELECT
        s.SALE_LINE_ID AS SRC_SYS_ID,
        CAST(s.SALE_LINE_ID AS VARCHAR) AS SALE_LINE_ID,
        s.CUSTOMER_ID,
        s.PRODUCT_ID,
        s.CONTRACT_ID,
        s.SUBMISSION_ID,
        s.SALE_TYPE,
        s.INV_DATE,
        s.INV_QTY,
        s.INV_AMT,
        s.DISC_REQUESTED,
        s.DISC_PAID,
        s.LINE_SEVERITY,
        s.INV_AMT AS GROSS_SALES,
        (s.INV_AMT - COALESCE(s.DISC_PAID, 0)) AS NET_AMOUNT,
        COALESCE(s.DISC_PAID, 0) AS DISCOUNT_AMOUNT,
        CASE WHEN s.INV_AMT = 0 THEN NULL ELSE (COALESCE(s.DISC_PAID, 0) / s.INV_AMT) * 100 END AS DISCOUNT_PERCENT,
        CASE WHEN COALESCE(s.LINE_SEVERITY, '') = 'HIGH' THEN TRUE ELSE FALSE END AS LINE_SEVERITY_FLAG,
        s.SRC_SYS_DATE_CREATED,
        s.SRC_SYS_DATE_UPDATED,
        s.ETL_DATE_CREATED,
        s.ETL_DATE_UPDATED,
        s.SOURCE_SYSTEM
    FROM {DATABASE}.{SCHEMA_RAW}.STG_DIRECT_SALES s

    UNION ALL

    SELECT
        s.SALE_LINE_ID AS SRC_SYS_ID,
        CAST(s.SALE_LINE_ID AS VARCHAR) AS SALE_LINE_ID,
        s.CUSTOMER_ID,
        s.PRODUCT_ID,
        s.CONTRACT_ID,
        s.SUBMISSION_ID,
        s.SALE_TYPE,
        s.INV_DATE,
        s.INV_QTY,
        s.INV_AMT,
        s.DISC_REQUESTED,
        s.DISC_PAID,
        s.LINE_SEVERITY,
        s.INV_AMT AS GROSS_SALES,
        (s.INV_AMT - COALESCE(s.DISC_PAID, 0)) AS NET_AMOUNT,
        COALESCE(s.DISC_PAID, 0) AS DISCOUNT_AMOUNT,
        CASE WHEN s.INV_AMT = 0 THEN NULL ELSE (COALESCE(s.DISC_PAID, 0) / s.INV_AMT) * 100 END AS DISCOUNT_PERCENT,
        CASE WHEN COALESCE(s.LINE_SEVERITY, '') = 'HIGH' THEN TRUE ELSE FALSE END AS LINE_SEVERITY_FLAG,
        s.SRC_SYS_DATE_CREATED,
        s.SRC_SYS_DATE_UPDATED,
        s.ETL_DATE_CREATED,
        s.ETL_DATE_UPDATED,
        s.SOURCE_SYSTEM
    FROM {DATABASE}.{SCHEMA_RAW}.STG_INDIRECT_SALES s
)
SELECT * FROM combined_sales;

-- 2. Curated Layer Dynamic Tables
CREATE OR REPLACE DYNAMIC TABLE {DATABASE}.{SCHEMA_CURATED}.DT_SALES_SUMMARY
  TARGET_LAG = 'DOWNSTREAM'
  WAREHOUSE = {WAREHOUSE}
AS
SELECT
    f.INV_DATE AS SALES_DATE,
    f.CUSTOMER_ID,
    f.PRODUCT_ID,
    f.CONTRACT_ID,
    f.SALE_TYPE,
    SUM(f.INV_QTY) AS TOTAL_QTY,
    SUM(f.GROSS_SALES) AS TOTAL_GROSS_SALES,
    SUM(f.NET_AMOUNT) AS TOTAL_NET_AMOUNT,
    SUM(f.DISCOUNT_AMOUNT) AS TOTAL_DISCOUNT,
    AVG(f.DISCOUNT_PERCENT) AS AVG_DISCOUNT_PERCENT,
    COUNT(*) AS SALES_COUNT,
    SUM(CASE WHEN f.LINE_SEVERITY_FLAG = TRUE THEN 1 ELSE 0 END) AS HIGH_SEVERITY_LINES,
    CURRENT_TIMESTAMP() AS ETL_DATE_CREATED
FROM {DATABASE}.{SCHEMA_CANONICAL}.DT_SALES_FACT f
GROUP BY
    f.INV_DATE,
    f.CUSTOMER_ID,
    f.PRODUCT_ID,
    f.CONTRACT_ID,
    f.SALE_TYPE;

CREATE OR REPLACE DYNAMIC TABLE {DATABASE}.{SCHEMA_CURATED}.DT_CUSTOMER_ANALYTICS
  TARGET_LAG = 'DOWNSTREAM'
  WAREHOUSE = {WAREHOUSE}
AS
SELECT
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    c.CUSTOMER_TYPE,
    COUNT(DISTINCT f.SALE_LINE_ID) AS TOTAL_ORDERS,
    SUM(f.INV_QTY) AS TOTAL_QTY,
    SUM(f.GROSS_SALES) AS TOTAL_GROSS_SALES,
    SUM(f.NET_AMOUNT) AS TOTAL_NET_AMOUNT,
    SUM(f.DISCOUNT_AMOUNT) AS TOTAL_DISCOUNT,
    AVG(f.DISCOUNT_PERCENT) AS AVG_DISCOUNT_PERCENT,
    MIN(f.INV_DATE) AS FIRST_PURCHASE_DATE,
    MAX(f.INV_DATE) AS LAST_PURCHASE_DATE,
    SUM(CASE WHEN f.LINE_SEVERITY_FLAG = TRUE THEN 1 ELSE 0 END) AS HIGH_SEVERITY_COUNT,
    CURRENT_TIMESTAMP() AS ETL_DATE_CREATED
FROM {DATABASE}.{SCHEMA_CANONICAL}.CUSTOMER_DIM c
LEFT JOIN {DATABASE}.{SCHEMA_CANONICAL}.DT_SALES_FACT f
    ON c.CUSTOMER_ID = f.CUSTOMER_ID
GROUP BY
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    c.CUSTOMER_TYPE;

CREATE OR REPLACE DYNAMIC TABLE {DATABASE}.{SCHEMA_CURATED}.DT_PRODUCT_PERFORMANCE
  TARGET_LAG = 'DOWNSTREAM'
  WAREHOUSE = {WAREHOUSE}
AS
SELECT
    p.PRODUCT_ID,
    p.PRODUCT_NAME,
    p.PRODUCT_CATEGORY,
    p.BRAND,
    SUM(f.INV_QTY) AS TOTAL_QTY,
    SUM(f.GROSS_SALES) AS TOTAL_GROSS_SALES,
    SUM(f.NET_AMOUNT) AS TOTAL_NET_AMOUNT,
    SUM(f.DISCOUNT_AMOUNT) AS TOTAL_DISCOUNT,
    AVG(f.DISCOUNT_PERCENT) AS AVG_DISCOUNT_PERCENT,
    COUNT(DISTINCT f.SALE_LINE_ID) AS TOTAL_TRANSACTIONS,
    SUM(CASE WHEN f.LINE_SEVERITY_FLAG = TRUE THEN 1 ELSE 0 END) AS HIGH_SEVERITY_COUNT,
    CURRENT_TIMESTAMP() AS ETL_DATE_CREATED
FROM {DATABASE}.{SCHEMA_CANONICAL}.PRODUCT_DIM p
LEFT JOIN {DATABASE}.{SCHEMA_CANONICAL}.DT_SALES_FACT f
    ON p.PRODUCT_ID = f.PRODUCT_ID
GROUP BY
    p.PRODUCT_ID,
    p.PRODUCT_NAME,
    p.PRODUCT_CATEGORY,
    p.BRAND;

