
  create or replace   view SALES.SALES_RAW_sales_raw.stg_direct_sales
  
  
  
  
  as (
    SELECT
    SALE_LINE_ID::NUMBER(38,0) AS SALE_LINE_ID,
    CUSTOMER_ID::NUMBER(38,0) AS CUSTOMER_ID,
    PRODUCT_ID::NUMBER(38,0) AS PRODUCT_ID,
    CONTRACT_ID::NUMBER(38,0) AS CONTRACT_ID,
    SUBMISSION_ID::NUMBER(38,0) AS SUBMISSION_ID,
    'DIRECT'::VARCHAR AS SALE_TYPE,
    INV_DATE::DATE AS INV_DATE,
    INV_QTY::NUMBER(18,2) AS INV_QTY,
    INV_AMT::NUMBER(18,2) AS INV_AMT,
    DISC_REQUESTED::NUMBER(18,2) AS DISC_REQUESTED,
    DISC_PAID::NUMBER(18,2) AS DISC_PAID,
    LINE_SEVERITY::VARCHAR AS LINE_SEVERITY,
    DATE_CREATED::TIMESTAMP_NTZ AS SRC_SYS_DATE_CREATED,
    DATE_UPDATED::TIMESTAMP_NTZ AS SRC_SYS_DATE_UPDATED,
    DATE_UPDATED::TIMESTAMP_NTZ AS DATE_UPDATED,
    CURRENT_TIMESTAMP() AS ETL_DATE_CREATED,
    CURRENT_TIMESTAMP() AS ETL_DATE_UPDATED,
    'sales'::VARCHAR AS SOURCE_SYSTEM
FROM SALES.SALES_RAW.DIRECT_SALE_LINES_RAW
  );

