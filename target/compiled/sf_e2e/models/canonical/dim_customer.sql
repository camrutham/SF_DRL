

SELECT
    c.CUSTOMER_ID,
    c.CUSTOMER_NUMBER,
    c.CUSTOMER_NAME,
    c.CUSTOMER_TYPE,
    c.INDUSTRY,
    c.ADDRESS,
    c.CITY,
    c.STATE,
    c.COUNTRY,
    c.EMAIL,
    c.PHONE,
    c.DATE_CREATED AS SRC_SYS_DATE_CREATED,
    c.DATE_UPDATED AS SRC_SYS_DATE_UPDATED,
    CURRENT_TIMESTAMP() AS DATE_CREATED,
    CURRENT_TIMESTAMP() AS DATE_UPDATED,
    'sales' AS SOURCE_SYSTEM
FROM SALES.SALES_RAW.CUSTOMER_RAW c


WHERE c.DATE_UPDATED > (SELECT MAX(COALESCE(SRC_SYS_DATE_UPDATED, DATE_UPDATED)) FROM SALES.SALES_RAW_sales_canonical.dim_customer)
   OR c.DATE_UPDATED > (SELECT MAX(COALESCE(SRC_SYS_DATE_UPDATED, DATE_UPDATED)) FROM SALES.SALES_RAW_sales_canonical.dim_customer)
