

WITH source_data AS (
    SELECT
        s.SALE_LINE_ID,
        s.CUSTOMER_ID,
        s.PRODUCT_ID,
        s.CONTRACT_ID,
        s.SUBMISSION_ID,
        s.SALE_TYPE,
        s.INV_DATE,
        s.INV_QTY,
        s.INV_AMT,
        s.DISC_REQUESTED,
        s.DISC_PAID,
        s.LINE_SEVERITY,
        s.INV_AMT AS GROSS_SALES,
        (s.INV_AMT - COALESCE(s.DISC_PAID, 0)) AS NET_AMOUNT,
        COALESCE(s.DISC_PAID, 0) AS DISCOUNT_AMOUNT,
        CASE WHEN s.INV_AMT = 0 THEN NULL ELSE (COALESCE(s.DISC_PAID, 0) / s.INV_AMT) * 100 END AS DISCOUNT_PERCENT,
        CASE WHEN COALESCE(s.LINE_SEVERITY, '') = 'HIGH' THEN TRUE ELSE FALSE END AS LINE_SEVERITY_FLAG,
        s.SRC_SYS_DATE_CREATED,
        s.SRC_SYS_DATE_UPDATED,
        s.ETL_DATE_CREATED,
        s.ETL_DATE_UPDATED,
        s.SOURCE_SYSTEM,
        s.DATE_UPDATED
    FROM SALES.sales_raw.stg_direct_sales s
)

SELECT
    SALE_LINE_ID,
    CUSTOMER_ID,
    PRODUCT_ID,
    CONTRACT_ID,
    SUBMISSION_ID,
    SALE_TYPE,
    INV_DATE,
    INV_QTY,
    INV_AMT,
    DISC_REQUESTED,
    DISC_PAID,
    LINE_SEVERITY,
    GROSS_SALES,
    NET_AMOUNT,
    DISCOUNT_AMOUNT,
    DISCOUNT_PERCENT,
    LINE_SEVERITY_FLAG,
    SRC_SYS_DATE_CREATED,
    SRC_SYS_DATE_UPDATED,
    ETL_DATE_CREATED,
    ETL_DATE_UPDATED,
    SOURCE_SYSTEM
FROM source_data


WHERE DATE_UPDATED > (SELECT MAX(COALESCE(SRC_SYS_DATE_UPDATED, DATE_UPDATED)) FROM SALES.sales_canonical.sales_fact_direct)
   OR SRC_SYS_DATE_UPDATED > (SELECT MAX(COALESCE(SRC_SYS_DATE_UPDATED, DATE_UPDATED)) FROM SALES.sales_canonical.sales_fact_direct)
